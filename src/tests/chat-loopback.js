// Local-only transport test; no cluster host is contacted.
const {Gio, GLib} = imports.gi;
imports.searchPath.unshift(GLib.build_filenamev([GLib.get_current_dir(), 'src']));
const Chat = imports.services.chat;
function assert(ok, message) { if (!ok) throw new Error(message); }
assert(Chat.normalizePeer('C2R3S4').host === 'c2r3s4.42gyeongsan.kr', 'seat normalization');
assert(Chat.normalizePeer('bad host') === null, 'invalid host rejected');
const reservation = new Gio.SocketListener();
const port = reservation.add_any_inet_port(null);
reservation.close();
const blockedService = new Chat.ChatService(port, ['c2r3s4']);
assert(blockedService.open('c2r3s4') === null, 'blocked seat cannot connect');
const blockedPeer = blockedService._peer('c2r3s4', 'c2r3s4.42gyeongsan.kr');
let blockedMessages = 0;
blockedService.connect('message', () => blockedMessages++);
blockedService._record(blockedPeer, 'in', 'blocked');
assert(blockedMessages === 0 && blockedPeer.history.length === 0, 'blocked message never recorded or emitted');
blockedService.setBlocked(['c2r3s4']);
assert(blockedService.peers.length === 0, 'blocking removes existing peer');
blockedService.setBlocked([]);
assert(blockedService._blocked.size === 0, 'unblock clears filter');
blockedService.setBlocked(['c2r3']);
assert(blockedService.isBlocked('c2r3s4'), 'line blocks its seats');
assert(!blockedService.isBlocked('c2r30s4'), 'line boundary');
blockedService.setBlocked(['c2']);
assert(blockedService.isBlocked('c2r8s9'), 'cluster blocks its lines');
assert(!blockedService.isBlocked('c20r8s9'), 'cluster boundary');
blockedService.destroy();
const service = new Chat.ChatService(port);
const loop = new GLib.MainLoop(null, false);
let received = false;
const timeout = GLib.timeout_add_seconds(GLib.PRIORITY_DEFAULT, 5, () => { loop.quit(); return GLib.SOURCE_REMOVE; });
service.connect('message', (_service, key, entry) => {
    if (entry.dir !== 'in') return;
    assert(entry.text === 'Local test <b>plain text</b>', 'payload preserved');
    assert(service.peer(key).unread === 1, 'unread incoming');
    service.markRead(key);
    assert(service.peer(key).unread === 0, 'read acknowledgement');
    received = true;
    loop.quit();
});
service.start();
assert(service.state === 'listening', 'listener starts');
assert(service.open('127.0.0.1') === null, 'IP input rejected');
assert(service.open('example.com') === null, 'hostname input rejected');
// Bypass seat-only UI/API for this local transport test.
const peer = service._peer('localhost', '127.0.0.1');
const key = peer.key;
service.send(key, 'Local test <b>plain text</b>');
loop.run();
if (received) GLib.source_remove(timeout);
service.destroy();
assert(received, 'loopback message received before timeout');
print('PASS: seat normalization, local TCP send/receive, plain text, unread tracking, cleanup');
